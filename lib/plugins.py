DATA_DIR = os.environ.get("CLANKER_DATA", "/data/clanker")
PLUGINS_DIR = os.path.join(DATA_DIR, "plugins")


def ensure_plugin_dirs():
    """Create plugin directories."""
    for subdir in ["analyzers", "health-checks"]:
        os.makedirs(os.path.join(PLUGINS_DIR, subdir), exist_ok=True)


def discover_plugins(plugin_type="analyzers"):
    """Find all plugins of a given type."""
    plugin_dir = os.path.join(PLUGINS_DIR, plugin_type)
    if not os.path.isdir(plugin_dir):
        return []

    plugins = []
    for f in sorted(os.listdir(plugin_dir)):
        path = os.path.join(plugin_dir, f)
        if os.access(path, os.X_OK) or f.endswith(".py") or f.endswith(".sh"):
            plugins.append({"name": f, "path": path, "type": plugin_type})
    return plugins


def run_plugin(plugin, stdin_data=None, timeout=60):
    """Run a plugin and capture output.

    Plugins follow the Unix convention:
    - Read JSONL from stdin
    - Write findings to stdout (JSONL or text)
    - Exit 0 on success, non-zero on failure
    """
    cmd = plugin["path"]
    if cmd.endswith(".py"):
        cmd = f"python3 {cmd}"
    elif cmd.endswith(".sh"):
        cmd = f"bash {cmd}"

    try:
        proc = subprocess.run(
            cmd, shell=True,
            input=stdin_data,
            capture_output=True, text=True,
            timeout=timeout
        )
        return {
            "name": plugin["name"],
            "exit_code": proc.returncode,
            "stdout": proc.stdout,
            "stderr": proc.stderr,
        }
    except subprocess.TimeoutExpired:
        return {
            "name": plugin["name"],
            "exit_code": -1,
            "stdout": "",
            "stderr": f"Timed out after {timeout}s",
        }


def scaffold_watchdog(name: str, kind: str = "config-drift",
                      out_dir: str | None = None) -> str:
    """Scaffold a new health-check 'drift watchdog' plugin.

    Class-of-bug fix from eigenstateresearch Session 7 (2026-04-18):
    every config that encodes an external-world fact (city → ICAO
    map, API contracts, etc.) needs a paired watchdog plugin to alert
    on drift. Hand-writing each was 200 lines of boilerplate; this
    generator emits a runnable template.

    Parameters
    ----------
    name : short slug like 'station-drift', 'forecast-bias', 'wu-schema'.
        The plugin will be created as `pwb-<name>.py` (or `<name>.py` if
        no project prefix is appropriate).
    kind : currently 'config-drift' (compares a local dict literal
        against a fetched external source). Future: 'api-contract',
        'sql-schema', 'param-bounds'.
    out_dir : where to write. Defaults to the project's clanker_plugins
        dir if running inside a project, else /data/clanker/plugins/health-checks.

    Returns the absolute path of the created plugin.
    """
    if not name or not name.replace("-", "").replace("_", "").isalnum():
        raise ValueError(f"invalid name: {name!r}")
    target_dir = out_dir or os.path.join(PLUGINS_DIR, "health-checks")
    os.makedirs(target_dir, exist_ok=True)
    fname = name if name.endswith(".py") else f"{name}.py"
    target = os.path.join(target_dir, fname)
    if os.path.exists(target):
        raise FileExistsError(f"{target} already exists — refusing to overwrite")

    template = _watchdog_template(name=name, kind=kind)
    with open(target, "w") as f:
        f.write(template)
    os.chmod(target, 0o755)
    return target


