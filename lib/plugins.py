def run_all_analyzers(session_data=None):
    """Run all analyzer plugins against session data."""
    plugins = discover_plugins("analyzers")
    if not plugins:
        print("No analyzer plugins found.")
        print(f"Drop scripts in: {os.path.join(PLUGINS_DIR, 'analyzers')}/")
        print("Interface: read JSONL from stdin, write findings to stdout")
        return []

    results = []
    for p in plugins:
        print(f"Running analyzer: {p['name']}")
        result = run_plugin(p, stdin_data=session_data)
        results.append(result)
        if result["stdout"]:
            print(result["stdout"])
        if result["stderr"]:
            print(f"  STDERR: {result['stderr']}", end="")
    return results


def run_all_health_checks():
    """Run all health check plugins."""
    plugins = discover_plugins("health-checks")
    if not plugins:
        return []

    results = []
    for p in plugins:
        result = run_plugin(p, timeout=30)
        results.append(result)
    return results


def list_plugins():
    """List all installed plugins."""
    ensure_plugin_dirs()
    print("=== Clanker Plugins ===\n")
    for ptype in ["analyzers", "health-checks"]:
        plugins = discover_plugins(ptype)
        print(f"{ptype}/ ({len(plugins)} plugins)")
        if plugins:
            for p in plugins:
                print(f"  {p['name']}")
        else:
            print(f"  (empty — drop scripts here: {os.path.join(PLUGINS_DIR, ptype)}/)")
        print()
